import type { ClapParams, CymbalParams, HatParams, KickParams, PercParams, SnareParams, TomParams, Lofi, BassKind, StabTone, ChordKind, FxKind } from './voices';

/**
 * Drum-machine "characters": one parameter set per voice, voiced to a style.
 * Each becomes a 16-pad synth kit (kits.ts) and sixteen library sounds.
 * The names describe a sound, not a product.
 */

export type Role = 'kick' | 'snare' | 'clap' | 'chh' | 'ohh' | 'tomL' | 'tomM' | 'tomH' | 'rim' | 'shaker' | 'percA' | 'percB' | 'crash' | 'ride' | 'bass' | 'stab' | 'fx';

/** Pad order for a full kit: drums first, so a groove lands on the same pads in every kit. */
