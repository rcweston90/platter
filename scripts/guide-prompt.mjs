/**
 * Writes api/_guide/prompt.json: the booth guide's instructions and tools,
 * made from the control registry (src/guide/prompt.ts and tools.ts), for the
 * server function api/guide.ts. The function reads this file instead of the
 * registry so it doesn't pull the audio engine into a serverless bundle, and
 * so the page can't send its own instructions to the model.
 *
 *   node scripts/guide-prompt.mjs           rewrite the file
 *   node scripts/guide-prompt.mjs --check   fail if the file is out of date (the build runs this)
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const file = `${root}api/_guide/prompt.json`;

const out = await build({
  stdin: {
    contents: `
      export { guideInstructions } from '${root}src/guide/prompt.ts';
      export { guideTools } from '${root}src/guide/tools.ts';
    `,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'error',
  loader: { '.css': 'empty', '.png': 'empty', '.svg': 'empty' },
});
const G = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);

const prompt = {
  note: 'Generated by scripts/guide-prompt.mjs from src/guide/prompt.ts and tools.ts. Do not edit by hand.',
  instructions: G.guideInstructions(),
  tools: G.guideTools().map((t) => ({ name: t.name, description: t.description, input_schema: t.parameters })),
};
const text = `${JSON.stringify(prompt, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let now = '';
  try {
    now = readFileSync(file, 'utf8');
  } catch {}
  if (now !== text) {
    console.error('api/_guide/prompt.json is out of date with the guide registry. Run: node scripts/guide-prompt.mjs');
    process.exit(1);
  }
  console.log('api/_guide/prompt.json is up to date');
} else {
  writeFileSync(file, text);
  console.log(`wrote api/_guide/prompt.json (${prompt.instructions.length} characters of instructions, ${prompt.tools.length} tools)`);
}
